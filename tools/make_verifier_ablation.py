def edge(ck, uid, p, q, t_draw, t_settle, dim=None):
    s, c1, c2, e = sa.seg(p, q)
    d = f"M{f(s[0])},{f(s[1])} C{f(c1[0])},{f(c1[1])} {f(c2[0])},{f(c2[1])} {f(e[0])},{f(e[1])}"
    L = sa.plen(sa.cubic_pts(s, c1, c2, e))
    return (sa.El(uid, "path", {"d": d, "fill": "none", "stroke": SW_LINE, "stroke-width": "1.8",
                                "stroke-linecap": "round"}, dash=f"{f(L)} {f(L)}")
            .track("o", ck.appear(t_draw, dur=0.05, dim=dim))
            .track("d", [(0.0, L), (t_draw, L), (t_draw + 0.45, 0.0), (ck.cycle, 0.0)])
            .track("c", [(0.0, AMBER), (t_settle, AMBER), (t_settle + 0.4, SW_LINE), (ck.cycle, SW_LINE)]))


def chip(cx, cy, text, fill):
    return (f'<text x="{f(cx)}" y="{f(cy - 12)}" text-anchor="middle" font-family="{MONO}" '
            f'font-size="9.5" font-weight="700" fill="{fill}">{text}</text>')


def node(ck, uid, cx, cy, kind, t_show, t_verdict, text=None, dim=None):
    """kind: ok / fail (terminal verdicts, with a glyph), hi / lo (a verifier score,
    ring only, the score above it), unknown (grey ring, '?')."""
    ring = (f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{R}" fill="{NODE_FILL}" stroke="{NODE_STROKE}" '
            f'stroke-width="1.6"/>')
    col = {"ok": TEAL, "hi": TEAL, "fail": ROSE, "lo": ROSE}.get(kind)
    body = ""
    if col:
        body = (f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{R}" fill="{NODE_FILL}" stroke="{col}" '
                f'stroke-width="1.8"/>')
    if kind == "ok":
        body += (f'<path d="{sa.check_d(cx, cy)}" fill="none" stroke="{TEAL}" stroke-width="1.6" '
                 f'stroke-linecap="round" stroke-linejoin="round"/>')
    elif kind == "fail":
        body += (f'<path d="{sa.cross_d(cx, cy)}" fill="none" stroke="{ROSE}" stroke-width="1.6" '
                 f'stroke-linecap="round"/>')
    if text is not None:
        body += chip(cx, cy, text, col or LABEL)
    verdict = (sa.El(uid + "-v", "g", children=[body], origin=(cx, cy))
               .track("o", ck.once(t_verdict)).track("s", ck.pop(t_verdict)))
    return sa.El(uid, "g", children=[ring, verdict]).track("o", ck.appear(t_show, dim=dim))


def value_chip(ck, uid, cx, cy, text, fill, t, dim=None):
    """A value that lands on a node later than the node itself (a rollout outcome)."""
    return sa.El(uid, "g", children=[chip(cx, cy, text, fill)]).track("o", ck.appear(t, dim=dim))


def token(ck, uid, points, t_arrive, up=False):
    """Indigo dash running down to the node selected next; amber back up with a value."""
    d, L = sa.chain_path(points)
    dur = max(0.25, L / 600) if not up else BACK
    t0 = t_arrive - dur
    near, far = 16.0, -(L - 16)
    a, b = (far, near) if up else (near, far)
    return (sa.El(uid, "path", {"d": d, "fill": "none", "stroke": AMBER if up else INDIGO,
                                "stroke-width": "3", "stroke-linecap": "round"}, dash=f"16 {f(L + 32)}")
            .track("o", [(0.0, 0.0), (t0, 0.0), (t0 + 0.03, 1.0), (t_arrive, 1.0), (t_arrive + 0.06, 0.0),
                         (ck.cycle, 0.0)])
            .track("d", [(0.0, a), (t0, a), (t_arrive, b), (ck.cycle, b)]))


def glow(ck, uid, points, t, gid):
    d, L = sa.chain_path(points)
    return (sa.El(uid, "path", {"d": d, "fill": "none", "stroke": f"url(#{gid})", "stroke-width": "3",
                                "stroke-linecap": "round", "stroke-linejoin": "round"},
                  dash=f"{f(L)} {f(L)}", cls="va-glow")
            .track("o", ck.appear(t, dur=0.05)).track("d", [(0.0, L), (t, L), (t + 1.0, 0.0), (ck.cycle, 0.0)]))


def goal(ck, uid, cx, cy, t):
    body = (f'<circle cx="{f(cx)}" cy="{f(cy)}" r="7.5" fill="{AMBER}"/>'
            f'<path d="{sa.check_d(cx, cy)}" fill="none" stroke="{SPACE}" stroke-width="1.9" '
            f'stroke-linecap="round" stroke-linejoin="round"/>')
    tr = ck.appear(t)
    tr[-3:] = [(ck.f1, 1.0), (ck.f1 + 0.3, 0.0), (ck.cycle, 0.0)]   # outlives the verdict it covers
    return sa.El(uid, "g", children=[body], origin=(cx, cy), cls="va-goal").track("o", tr).track("s", ck.pop(t))


def time_label(ck, uid, seconds, t):
    return (sa.El(uid, "g", children=[
        f'<text x="{VB_W - 8}" y="{VB_H - 9}" text-anchor="end" font-family="{MONO}" font-size="12" '
        f'font-weight="700" letter-spacing="1" fill="{AMBER}">{seconds} S / SUCCESS TRAJ.</text>'])
        .track("o", ck.appear(t, dur=0.3)))


def root():
    cx, cy = ROOT_XY
    return (f'<circle cx="{cx}" cy="{cy}" r="{R}" fill="{NODE_FILL}" stroke="{NODE_STROKE}" stroke-width="1.6"/>'
            + sa.label(cx, cy + 22, "START"))


class Tree:
    """Node positions and parents for one animation, with path helpers."""

    def __init__(self, pos, parent):
        self.pos, self.parent = dict(pos, R=ROOT_XY), parent

    def path(self, key):
        chain = [key]
        while chain[-1] != "R":
            chain.append(self.parent[chain[-1]])
        return [self.pos[k] for k in reversed(chain)]


def finish(ck, P, tree, path_pts, t_glow, gid, seconds):
    return ([glow(ck, f"{P}-glow", path_pts, t_glow, gid),
             goal(ck, f"{P}-goal", *path_pts[-1], t_glow + 1.0),
             time_label(ck, f"{P}-time", seconds, t_glow + 1.3)])


