# ----------------------------------------------------------------------------
# A clock per animation: the fades, the reduced-motion still and the keyframe
# percentages all hang off its cycle.
# ----------------------------------------------------------------------------
class Clock:
    def __init__(self, cycle):
        self.cycle = cycle
        self.f0, self.f1 = cycle - 1.4, cycle - 0.7   # everything clears before the loop restarts
        self.hold = cycle - 2.0                      # the still shown under prefers-reduced-motion

    def appear(self, t_in, dur=0.18, level=1.0, dim=None):
        p = [(0.0, 0.0), (t_in, 0.0), (t_in + dur, level)]
        if dim:
            t_dim, to = dim
            p += [(t_dim, level), (t_dim + 0.5, to)]
            level = to
        return p + [(self.f0, level), (self.f1, 0.0), (self.cycle, 0.0)]

    def window(self, t_in, t_out, dur=0.18, out=0.3):
        """Shown from t_in, gone again by t_out + out -- a rollout that is discarded."""
        return [(0.0, 0.0), (t_in, 0.0), (t_in + dur, 1.0), (t_out, 1.0), (t_out + out, 0.0),
                (self.cycle, 0.0)]

    def pop(self, t_in, lo=0.6):
        return [(0.0, lo), (t_in, lo), (t_in + 0.12, 1.15), (t_in + 0.26, 1.0), (self.cycle, 1.0)]

    def once(self, t_in, dur=0.18):
        return [(0.0, 0.0), (t_in, 0.0), (t_in + dur, 1.0), (self.cycle, 1.0)]

    def pct(self, t):
        return f(t / self.cycle * 100) + "%"


