def css_for(x, ck):
    decl = [f"animation-name: {x.uid};"]
    if "s" in x.tracks:
        cx, cy = x.origin
        decl += ["transform-box: view-box;", f"transform-origin: {f(cx)}px {f(cy)}px;"]
    if "d" in x.tracks:
        decl.append(f"stroke-dasharray: {x.dash};")
    hold = [sa.PROP_CSS[p](x.value(p, ck.hold)) for p in x.tracks]
    out = [f"#{x.uid} {{ " + " ".join(decl + hold) + " }", f"@keyframes {x.uid} {{"]
    for t in sorted({t for tr in x.tracks.values() for t, _ in tr}):
        parts = [sa.PROP_CSS[p](v) for p, tr in x.tracks.items() for tt, v in tr if abs(tt - t) < 1e-9]
        out.append(f"  {ck.pct(t)} {{ " + " ".join(parts) + " }")
    out.append("}")
    return "\n".join(out)


