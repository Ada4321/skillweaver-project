def build_verifier(seconds):
    P = "va-v"
    tree = Tree({"A": (110, 70), "A2": (110, 140), "B": (190, 70), "B2": (190, 125),
                 "C2": (270, 30), "C": (270, 70), "D": (350, 70), "D2": (350, 125)},
                {"A": "R", "A2": "R", "B": "A", "B2": "A", "C": "B", "C2": "B", "D": "C", "D2": "C"})
    # (parent, children in execution order with (kind, score shown), best child)
    plan = [("R", [("A", "hi", "0.8"), ("A2", "lo", "0.3")], "A"),
            ("A", [("B", "hi", "0.9"), ("B2", "lo", "0.2")], "B"),
            ("B", [("C2", "lo", "0.4"), ("C", "hi", "0.7")], "C"),
            ("C", [("D", "ok", None), ("D2", "fail", None)], None)]
    win = ["R", "A", "B", "C", "D"]
    t, sched = 0.5, []
    for parent, kids, best in plan:
        sched.append((t, parent, kids, best))
        t_done = t + 2 * EXEC
        t = t_done + BACK + 0.1 + SEL + 0.05 if best else t_done
    t_glow = sched[-1][0] + VERDICT + EXEC + 0.15     # after both children of the last expansion are judged
    ck = Clock(t_glow + 4.3)
    dim = (t_glow, 0.35)
    edges, nodes, tokens = [], [], []
    for t0, parent, kids, best in sched:
        if parent != "R":
            tokens.append(token(ck, f"{P}-sel-{parent}", tree.path(parent), t0 - 0.05))
        for k, (child, kind, score) in enumerate(kids):
            t_v = t0 + VERDICT + k * EXEC
            keep = child in win
            edges.append(edge(ck, f"{P}-e-{child}", tree.pos[parent], tree.pos[child], t0 + k * EXEC, t_v,
                              dim=None if keep else dim))
            nodes.append(node(ck, f"{P}-{child}", *tree.pos[child], kind, t0 + k * EXEC + 0.3, t_v, score,
                              dim=None if keep else dim))
        if best:
            tokens.append(token(ck, f"{P}-up-{best}", tree.path(best), t0 + 2 * EXEC + BACK, up=True))
    pts = [tree.pos[k] for k in win]
    els = ([sa.gradient("vaWinV", pts[0][0], pts[-1][0])] + edges + tokens + [root()] + nodes
           + finish(ck, P, tree, pts, t_glow, "vaWinV", seconds))
    return ck, els


