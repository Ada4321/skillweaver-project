def rollout(ck, uid, start, steps, ok, t0, t_gone):
    """Execute the downstream skills from `start` to depth 4, one EXEC each: small
    dashed nodes along the node's own row, the terminal judged. Discarded at
    t_gone unless it is the successful one (t_gone None)."""
    x0, y = start
    xs = [x for x in X if x > x0][:steps]
    out, prev = [], x0
    for k, x in enumerate(xs):
        t_in = t0 + k * EXEC
        last = k == len(xs) - 1
        g = (f'<path d="M{f(prev + (R if k == 0 else R_ROLL))},{f(y)} L{f(x - R_ROLL)},{f(y)}" stroke="{NODE_STROKE}" '
             f'stroke-width="1.3" stroke-dasharray="2.5 3.5" stroke-linecap="round" fill="none"/>'
             f'<circle cx="{f(x)}" cy="{f(y)}" r="{R_ROLL}" fill="{NODE_FILL}" stroke="{NODE_STROKE}" '
             f'stroke-width="1.3" stroke-dasharray="2 2"/>')
        if last:
            col = TEAL if ok else ROSE
            glyph = (f'<path d="{sa.check_d(x, y, 0.8)}" fill="none" stroke="{col}" stroke-width="1.5" '
                     f'stroke-linecap="round" stroke-linejoin="round"/>' if ok else
                     f'<path d="{sa.cross_d(x, y, 2.1)}" fill="none" stroke="{col}" stroke-width="1.5" '
                     f'stroke-linecap="round"/>')
            g += (f'<circle cx="{f(x)}" cy="{f(y)}" r="{R_ROLL}" fill="{NODE_FILL}" stroke="{col}" '
                  f'stroke-width="1.5"/>' + glyph)
        el = sa.El(f"{uid}-{k}", "g", children=[g])
        el.track("o", ck.appear(t_in, dur=0.25) if t_gone is None else ck.window(t_in, t_gone))
        out.append(el)
        prev = x
    return out, [(x, y) for x in xs]


def build_rollout(seconds):
    P = "va-r"
    tree = Tree({"A": (110, 65), "A2": (110, 150), "B2": (190, 30), "B": (190, 100), "E": (190, 150)},
                {"A": "R", "A2": "R", "B": "A", "B2": "A", "E": "A2"})
    depth = {"A": 1, "A2": 1, "B": 2, "B2": 2, "E": 2}
    # (parent, children in execution order with their rollout outcome). All zero
    # so far means the next pick is uniform too; the E rollout finally succeeds.
    plan = [("R", [("A", False), ("A2", False)]),
            ("A", [("B2", False), ("B", False)]),
            ("A2", [("E", True)])]
    edges, nodes, tokens, rolls, chips = [], [], [], [], []
    t = 0.5
    events = []
    for parent, kids in plan:
        if parent != "R":
            events.append(("sel", parent, t - 0.05))
        for child, ok in kids:
            steps = 4 - depth[child]
            t_exec = t
            t_roll = t + EXEC
            t_term = t_roll + (steps - 1) * EXEC + VERDICT
            events.append(("child", parent, child, ok, t_exec, t_roll, t_term))
            if ok:
                t_glow = t_term + 0.25
                break
            t = t_term + 0.1 + BACK + 0.1
        else:
            t += SEL
            continue
        break
    ck = Clock(t_glow + 4.3)
    win_nodes = ["R", "A2", "E"]
    dim = (t_glow, 0.35)
    win_tail = []
    for ev in events:
        if ev[0] == "sel":
            tokens.append(token(ck, f"{P}-sel-{ev[1]}", tree.path(ev[1]), ev[2]))
            continue
        _, parent, child, ok, t_exec, t_roll, t_term = ev
        keep = child in win_nodes
        edges.append(edge(ck, f"{P}-e-{child}", tree.pos[parent], tree.pos[child], t_exec, t_exec + VERDICT,
                          dim=None if keep else dim))
        nodes.append(node(ck, f"{P}-{child}", *tree.pos[child], "unknown", t_exec + 0.3, t_exec + VERDICT,
                          None, dim=None if keep else dim))
        steps = 4 - depth[child]
        t_gone = None if ok else t_term + 0.1 + BACK
        chain, pts = rollout(ck, f"{P}-roll-{child}", tree.pos[child], steps, ok, t_roll, t_gone)
        rolls += chain
        if ok:
            win_tail = pts
        else:
            tokens.append(token(ck, f"{P}-up-{child}", tree.path(child), t_term + 0.1 + BACK, up=True))
            chips.append(value_chip(ck, f"{P}-val-{child}", *tree.pos[child], "0", ROSE,
                                    t_term + 0.1 + BACK, dim=None if keep else dim))
    pts = [tree.pos[k] for k in win_nodes] + win_tail
    els = ([sa.gradient("vaWinR", pts[0][0], pts[-1][0])] + edges + rolls + tokens + [root()] + nodes + chips
           + finish(ck, P, tree, pts, t_glow, "vaWinR", seconds))
    return ck, els


