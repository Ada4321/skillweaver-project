def patch_html(path, block):
    h = path.read_text()
    p0 = h.index('id="panel-abl-verifier"')
    p1 = h.find('id="panel-abl-', p0 + 10)
    p1 = len(h) if p1 == -1 else p1
    ind = "        "
    new = "\n".join((ind + ln) if ln.strip() else ln for ln in block.split("\n"))
    if BEGIN_H in h[p0:p1]:
        a = h.index(BEGIN_H, p0)
        b = h.index(END_H, a) + len(END_H)
    else:
        a = h.index('<div class="media media--placeholder">', p0)
        assert a < p1, "placeholder not inside #panel-abl-verifier"
        b = h.index("</div>", h.index("placeholder__text", a)) + len("</div>")
    a = h.rindex("\n", 0, a) + 1
    path.write_text(h[:a] + new + h[b:])


def patch_css(path, block):
    c = path.read_text()
    if BEGIN_C in c:
        a, b = c.index(BEGIN_C), c.index(END_C) + len(END_C)
        c = c[:a] + block + c[b:]
    else:
        c = c.rstrip("\n") + "\n\n" + block + "\n"
    path.write_text(c)


def frames(outdir, anims, n=8):
    import cairosvg
    from PIL import Image, ImageDraw
    cols = []
    for ck, els in anims:
        tiles = []
        for i in range(n):
            t = ck.cycle * (i + 0.5) / n if i < n - 1 else ck.hold
            svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VB_W} {VB_H}" width="{VB_W}" '
                   f'height="{VB_H}"><rect width="100%" height="100%" fill="{SPACE}"/>'
                   + "".join(sa.render(e, "frame", t) for e in els) + "</svg>")
            img = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode()))).convert("RGB")
            tile = Image.new("RGB", (VB_W, VB_H + 18), "white")
            ImageDraw.Draw(tile).text((6, 3), f"t = {t:.1f} / {ck.cycle:.1f} s", fill=(20, 20, 20))
            tile.paste(img, (0, 18))
            tiles.append(tile)
        cols.append(tiles)
    gap = 12
    tw, th = cols[0][0].size
    sheet = Image.new("RGB", (len(cols) * tw + (len(cols) - 1) * gap, n * th + (n - 1) * gap), (150, 156, 166))
    for c, tiles in enumerate(cols):
        for r, tile in enumerate(tiles):
            sheet.paste(tile, (c * (tw + gap), r * (th + gap)))
    outdir.mkdir(parents=True, exist_ok=True)
    p = outdir / "verifier_ablation_frames.png"
    sheet.save(p)
    return p


