#!/usr/bin/env python3
"""Generate the Verifier-vs-no-Verifier panel of the Ablations section.

Two slides behind the page's left/right carousel (.carousel in css/style.css,
[data-carousel] in js/nav.js):

  Search guidance    Three search animations, one per configuration of
                     tab:verifier-ablation (a), over the table itself.
  Success detection  tab:verifier-ablation (b), with the handcrafted success
                     rules it is scored against (app:verifier_ablation).

The animations speak the visual language of the MCTS-vs-linear panel
(tools/make_search_ablation.py, whose element model and geometry helpers are
imported here): dark space panel, small dark nodes, amber for an edge being
grown, teal/rose verdicts, an indigo token running down to the node selected
next, an amber one running back up with a value, the teal->indigo->amber
gradient for the accepted path.

  w/ Verifier, w/o Rollout   the verifier scores each new node on the spot;
                             the score is backed up and the best frontier node
                             is expanded next, so the search walks straight in.
  w/o Verifier, w/o Rollout  no intermediate reward: children are "?", the next
                             node is drawn uniformly from the frontier, and only
                             a terminal step says whether a branch worked.
  w/o Verifier, w/ Rollout   standard MCTS: every new node is rolled out to a
                             terminal state, the outcome is backed up and the
                             rollout thrown away -- each step costs a full chain.

Each loops on its own clock (they are not time-matched); what each costs per
successful trajectory is the label it ends on, read from the paper.

Numbers are parsed from the paper source, not retyped. Re-run after they
change:

    python3 tools/make_verifier_ablation.py [--frames DIR]

--frames writes verifier_ablation_frames.png into DIR (keep it outside the
repo): stills rendered with cairosvg, since there is no browser on the cluster.
"""
