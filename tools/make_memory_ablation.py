#!/usr/bin/env python3
"""Generate the Memory-vs-no-Memory panel of the Ablations section.

One wide animation of the memory loop, over tab:memory-ablation from the paper:

  PAST SEARCH --distill--> MEMORY LIBRARY --retrieve top-k--> NEW SEARCH

  Generation  a past search (fork into a lying mug) fails; the failure is traced
              back to its earliest cause, the trajectory is distilled by a VLM,
              and a new entry lands in the library (app:memory_module).
  Retrieval   a new task (toothbrush into a lying cup) arrives; the selector VLM
              pulls the top-2 entries into the agent's context, and the search
              sets the cup upright before inserting -- the prerequisite the
              paper credits for Toothbrush -> Lying Cup going from 0% to 80%.

The library entries are verbatim keys from tab:memory_examples, their one-line
summaries shortened from the entries. Pairing that particular entry with that
past search is illustrative: both tasks come from the paper's task lists, but
the paper does not say which search produced which entry.

Same visual language and element model as the other two ablation animations
(tools/make_search_ablation.py, tools/make_verifier_ablation.py).

    python3 tools/make_memory_ablation.py [--frames DIR]
"""
import argparse
import io
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import chartlib  # noqa: E402
import make_search_ablation as sa  # noqa: E402
import make_verifier_ablation as va  # noqa: E402  (Clock, edge, node, token, glow, goal, css_for)

ROOT = Path(__file__).resolve().parent.parent
DEF_HTML = ROOT / "index.html"
DEF_CSS = ROOT / "css" / "style.css"
TEX = va.TEX

BEGIN_H = "<!-- >>> MEMORY ABLATION — generated by tools/make_memory_ablation.py, do not edit by hand >>> -->"
END_H = "<!-- <<< MEMORY ABLATION <<< -->"
BEGIN_C = "/* >>> MEMORY ABLATION — generated by tools/make_memory_ablation.py, do not edit by hand >>> */"
END_C = "/* <<< MEMORY ABLATION <<< */"

SPACE, SW_LINE, LABEL = sa.SPACE, sa.SW_LINE, sa.LABEL
NODE_FILL, NODE_STROKE = sa.NODE_FILL, sa.NODE_STROKE
TEAL, INDIGO, AMBER, ROSE = sa.TEAL, sa.INDIGO, sa.AMBER, sa.ROSE
MONO, R, f = sa.MONO, sa.R, sa.f
TEXT = "#D7DCE5"                       # primary text on the space panel

VB_W, VB_H = 1090, 300
EXEC, VERDICT = 0.8, 0.6

# Library: newest entry lands in the top slot.
CARD_X, CARD_W, CARD_H = 430, 300, 40
SLOTS = [44, 92, 140, 188, 236]
NEW = ("prepare container before insertion", "lying cup or mug: set it upright before inserting")
OLD = [("place beside target", "&#8220;beside&#8221; = the vacant spot next to it, not on it"),
       ("align elongated object for insertion", "long axis along the container's vertical axis"),
       ("straighten up objects", "upright axis to world vertical, back in its place"),
       ("place into side-opening container", "approach from the side; a top-down place collides")]
RETRIEVED = [0, 2]                     # slots the selector pulls: the new entry, and "align elongated ..."

# Past search (left) and new search (right).
P_ROOT, P_N1, P_N2 = (45, 150), (135, 150), (225, 150)
DISTILL = (280, 130, 100, 40)          # x, y, w, h
RETRIEVE = (780, 92, 150, 40)
N_X = [795, 860, 925, 990, 1055]
N_Y = 215
N_STEPS = ["pick cup", "upright", "pick brush", "insert"]


def text(x, y, s, size=10, fill=LABEL, anchor="start", weight=None, spacing=None):
    w = f' font-weight="{weight}"' if weight else ""
    ls = f' letter-spacing="{spacing}"' if spacing else ""
    return (f'<text x="{f(x)}" y="{f(y)}" text-anchor="{anchor}" font-family="{MONO}" font-size="{size}"'
            f'{w}{ls} fill="{fill}">{s}</text>')


def title(x, y, s, anchor="start"):
    return text(x, y, s, 10, LABEL, anchor, spacing=1.5)


def box(x, y, w, h, stroke=SW_LINE, fill=NODE_FILL, width=1.4, dash=None):
    da = f' stroke-dasharray="{dash}"' if dash else ""
    return (f'<rect x="{f(x)}" y="{f(y)}" width="{f(w)}" height="{f(h)}" rx="8" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{width}"{da}/>')


def start(xy):
    x, y = xy
    return (f'<circle cx="{x}" cy="{y}" r="{R}" fill="{NODE_FILL}" stroke="{NODE_STROKE}" stroke-width="1.6"/>'
            + sa.label(x, y + 22, "START"))


def card_body(y, key, line):
    return (text(CARD_X + 12, y + 17, key, 11, TEXT, weight=700)
            + text(CARD_X + 12, y + 31, line, 9.5, LABEL))


def flow(ck, uid, d, L, t_arrive, color, dur=0.6):
    """A dash running along a guide path, arriving at t_arrive."""
    t0 = t_arrive - dur
    return (sa.El(uid, "path", {"d": d, "fill": "none", "stroke": color, "stroke-width": "3",
                                "stroke-linecap": "round"}, dash=f"16 {f(L + 32)}")
            .track("o", [(0.0, 0.0), (t0, 0.0), (t0 + 0.03, 1.0), (t_arrive, 1.0), (t_arrive + 0.06, 0.0),
                         (ck.cycle, 0.0)])
            .track("d", [(0.0, 16.0), (t0, 16.0), (t_arrive, -(L - 16)), (ck.cycle, -(L - 16))]))


def curve(p, q):
    """Horizontal-tangent cubic from p to q, with its length."""
    (x1, y1), (x2, y2) = p, q
    cx = (x1 + x2) / 2
    pts = sa.cubic_pts(p, (cx, y1), (cx, y2), q)
    return f"M{f(x1)},{f(y1)} C{f(cx)},{f(y1)} {f(cx)},{f(y2)} {f(x2)},{f(y2)}", sa.plen(pts)


def guide(d):
    return (f'<path d="{d}" fill="none" stroke="{SW_LINE}" stroke-width="1.3" stroke-dasharray="3 4" '
            f'stroke-linecap="round"/>')


def build():
    P = "ma"
    # ---- timeline ----------------------------------------------------------
    t_instr_a = 0.4
    t_n1, t_n2 = 0.7, 0.7 + EXEC + 0.2                 # edges start growing
    v_n1, v_n2 = t_n1 + VERDICT, t_n2 + VERDICT
    t_trace = v_n2 + 0.9                               # rose trace arrives back at the root
    t_cause = t_trace + 0.1
    t_distill = t_cause + 1.0                          # flow into the distill box arrives
    t_card = t_distill + 1.1                           # new entry lands
    t_instr_b = t_card + 1.2
    t_pick = t_instr_b + 0.9                           # selector marks the top-2
    t_ctx = t_pick + 0.9                               # entries arrive in the agent context
    t_root = t_ctx + 0.7
    steps = [t_root + 0.25 + k * (EXEC + 0.05) for k in range(4)]
    t_glow = steps[-1] + VERDICT + 0.3
    ck = va.Clock(t_glow + 4.6)

    els = [sa.gradient("maWin", N_X[0], N_X[-1])]

    # ---- static scaffold (visible throughout, so a paused frame still reads) ---
    dx, dy, dw, dh = DISTILL
    rx, ry, rw, rh = RETRIEVE
    d_in = f"M{P_N2[0] + R},{P_N2[1]} L{dx},{dy + dh / 2}"
    L_in = dx - (P_N2[0] + R)
    d_out, L_out = curve((dx + dw, dy + dh / 2), (CARD_X, SLOTS[0] + CARD_H / 2))
    d_ret = [curve((CARD_X + CARD_W, SLOTS[s] + CARD_H / 2), (rx, ry + rh / 2)) for s in RETRIEVED]
    d_ctx = f"M{rx + 22},{ry + rh} L{N_X[0]},{N_Y - R}"
    L_ctx = ((N_X[0] - rx - 22) ** 2 + (N_Y - R - ry - rh) ** 2) ** 0.5
    static = [title(30, 26, "PAST SEARCH"), title(CARD_X + CARD_W / 2, 26, "MEMORY LIBRARY", "middle"),
              title(780, 26, "NEW SEARCH"),
              guide(d_in), guide(d_out), guide(d_ctx)] + [guide(d) for d, _ in d_ret] + [
              box(dx, dy, dw, dh), text(dx + dw / 2, dy + 17, "DISTILL", 10.5, TEXT, "middle", 700, 1),
              text(dx + dw / 2, dy + 31, "VLM", 9, LABEL, "middle"),
              box(rx, ry, rw, rh), text(rx + rw / 2, ry + 17, "RETRIEVE TOP-2", 10.5, TEXT, "middle", 700, 1),
              text(rx + rw / 2, ry + 31, "selector VLM", 9, LABEL, "middle"),
              box(CARD_X, SLOTS[0], CARD_W, CARD_H, fill="none", width=1.1, dash="3 4")]
    for (key, line), y in zip(OLD, SLOTS[1:]):
        static += [box(CARD_X, y, CARD_W, CARD_H), card_body(y, key, line)]
    els += static

    # ---- generation: the past search fails -----------------------------------
    els.append(sa.El(f"{P}-instr-a", "g", children=[
        text(30, 52, "&#8220;put the fork in the lying mug&#8221;", 11, TEXT)]).track("o", ck.appear(t_instr_a)))
    els.append(va.edge(ck, f"{P}-e1", P_ROOT, P_N1, t_n1, v_n1))
    els.append(va.edge(ck, f"{P}-e2", P_N1, P_N2, t_n2, v_n2))
    els.append(start(P_ROOT))
    els.append(va.node(ck, f"{P}-n1", *P_N1, "ok", t_n1 + 0.3, v_n1))
    els.append(va.node(ck, f"{P}-n2", *P_N2, "fail", t_n2 + 0.3, v_n2))
    els.append(sa.El(f"{P}-lab-a", "g", children=[
        sa.label(P_N1[0], P_N1[1] + 22, "pick fork"), sa.label(P_N2[0], P_N2[1] + 22, "insert")])
        .track("o", ck.appear(t_n1 + 0.3)))
    # traced back to its earliest cause: the first decision never set the mug upright
    d_tr, L_tr = sa.chain_path([P_ROOT, P_N1, P_N2])
    els.append(sa.El(f"{P}-trace", "path", {"d": d_tr, "fill": "none", "stroke": ROSE, "stroke-width": "3",
                                             "stroke-linecap": "round"}, dash=f"16 {f(L_tr + 32)}")
               .track("o", [(0.0, 0.0), (t_trace - 0.6, 0.0), (t_trace - 0.57, 1.0), (t_trace, 1.0),
                            (t_trace + 0.06, 0.0), (ck.cycle, 0.0)])
               .track("d", [(0.0, -(L_tr - 16)), (t_trace - 0.6, -(L_tr - 16)), (t_trace, 16.0), (ck.cycle, 16.0)]))
    els.append(sa.El(f"{P}-cause", "g", children=[
        f'<circle cx="{P_ROOT[0]}" cy="{P_ROOT[1]}" r="13" fill="none" stroke="{ROSE}" stroke-width="1.6" '
        f'stroke-dasharray="3 3"/>',
        text(30, 208, "earliest cause: the mug was", 9.5, ROSE),
        text(30, 222, "never set upright", 9.5, ROSE)]).track("o", ck.appear(t_cause, dur=0.3)))

    # ---- generation: distilled into a new entry -----------------------------
    els.append(flow(ck, f"{P}-to-distill", d_in, L_in, t_distill, AMBER, dur=0.4))
    els.append(sa.El(f"{P}-distill-hi", "g", children=[box(dx, dy, dw, dh, stroke=AMBER, fill="none", width=1.8)])
               .track("o", ck.window(t_distill, t_card + 0.2)))
    els.append(flow(ck, f"{P}-to-lib", d_out, L_out, t_card - 0.05, AMBER, dur=0.6))
    y0 = SLOTS[0]
    card_rect = (sa.El(f"{P}-card-rect", "rect", {"x": CARD_X, "y": y0, "width": CARD_W, "height": CARD_H,
                                                  "rx": "8", "fill": NODE_FILL, "stroke": AMBER, "stroke-width": "1.6"})
                 .track("c", [(0.0, AMBER), (t_card + 1.0, AMBER), (t_card + 1.6, SW_LINE), (ck.cycle, SW_LINE)]))
    els.append(sa.El(f"{P}-card", "g", children=[card_rect, card_body(y0, *NEW)],
                     origin=(CARD_X + CARD_W / 2, y0 + CARD_H / 2))
               .track("o", ck.appear(t_card)).track("s", ck.pop(t_card, lo=0.85)))

    # ---- retrieval: a new task pulls the top-2 into context ------------------
    els.append(sa.El(f"{P}-instr-b", "g", children=[
        text(780, 52, "&#8220;put the toothbrush in the lying cup&#8221;", 11, TEXT)])
        .track("o", ck.appear(t_instr_b)))
    for k, s in enumerate(RETRIEVED):
        y = SLOTS[s]
        els.append(sa.El(f"{P}-pick-{k}", "g", children=[
            box(CARD_X - 3, y - 3, CARD_W + 6, CARD_H + 6, stroke=AMBER, fill="none", width=1.8)])
            .track("o", ck.appear(t_pick + 0.15 * k)))
        d, L = d_ret[k]
        els.append(flow(ck, f"{P}-to-ctx-{k}", d, L, t_ctx, AMBER, dur=0.6))
    els.append(sa.El(f"{P}-retrieve-hi", "g", children=[box(rx, ry, rw, rh, stroke=AMBER, fill="none", width=1.8)])
               .track("o", ck.appear(t_ctx)))
    els.append(flow(ck, f"{P}-to-plan", d_ctx, L_ctx, t_root, INDIGO, dur=0.45))

    # ---- retrieval: the new search sets the cup upright first ----------------
    els.append(sa.El(f"{P}-root-b", "g", children=[start((N_X[0], N_Y))]).track("o", ck.appear(t_root)))
    pts = [(x, N_Y) for x in N_X]
    for k, t in enumerate(steps):
        els.append(va.edge(ck, f"{P}-f{k}", pts[k], pts[k + 1], t, t + VERDICT))
        els.append(va.node(ck, f"{P}-m{k}", *pts[k + 1], "ok", t + 0.3, t + VERDICT))
        els.append(sa.El(f"{P}-ml{k}", "g", children=[sa.label(pts[k + 1][0], N_Y + 22, N_STEPS[k])])
                   .track("o", ck.appear(t + 0.3)))
    els.append(va.glow(ck, f"{P}-glow", pts, t_glow, "maWin"))
    els.append(va.goal(ck, f"{P}-goal", *pts[-1], t_glow + 1.0))
    return ck, els


