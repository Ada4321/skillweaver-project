ARIA = ("Experience memory. Generation: a past search, putting a fork in a lying mug, fails; the failure is traced "
        "back to its earliest cause, the mug never being set upright, and a VLM distills the trajectory into a new "
        "library entry, prepare container before insertion. Retrieval: a new task, putting a toothbrush in a lying "
        "cup, arrives; a selector VLM retrieves the top two entries into the agent's context, and the search picks "
        "the cup, sets it upright, picks the toothbrush and inserts it.")


def html_block(ck, els, cols, rows):
    return "\n".join([
        BEGIN_H,
        '<figure class="abl-anim mem-anim">',
        '  <figcaption class="abl-anim__cap"><b>Experience memory</b><span>distilled after a search &middot; '
        'retrieved before the next</span></figcaption>',
        f'<svg class="search-anim" viewBox="0 0 {VB_W} {VB_H}" role="img" aria-label="{ARIA}">',
        "\n".join(sa.render(e, "page") for e in els),
        '</svg>',
        '</figure>'] + chart(cols, rows) + [END_H]).replace('class="sa', 'class="va')


def css_block(ck, els):
    static = f"""{BEGIN_C}
.mem-anim .va {{
  animation-duration: {f(ck.cycle)}s;
  animation-timing-function: linear;
  animation-iteration-count: infinite;
  animation-fill-mode: both;
}}

.mem-anim .va-glow {{
  filter: drop-shadow(0 0 7px rgba(255, 176, 32, 0.4));
}}

.mem-anim .va-goal {{
  filter: drop-shadow(0 0 8px rgba(255, 176, 32, 0.55));
}}

.mem-table {{
  margin-top: 22px;
}}
"""
    rules = "\n".join(va.css_for(x, ck) for x in sa.walk(els))
    tail = f"""
/* Without motion: rests at the HOLD state, both searches finished. */
@media (prefers-reduced-motion: reduce) {{
  .mem-anim .va {{
    animation: none !important;
  }}
}}
{END_C}"""
    return static + "\n" + rules + "\n" + tail


def patch_html(path, block):
    h = path.read_text()
    p0 = h.index('id="panel-abl-memory"')
    p1 = h.find("<!--\n", p0)
    ind = "        "
    new = "\n".join((ind + ln) if ln.strip() else ln for ln in block.split("\n"))
    if BEGIN_H in h[p0:p1]:
        a = h.index(BEGIN_H, p0)
        b = h.index(END_H, a) + len(END_H)
    else:
        a = h.index('<div class="media media--placeholder">', p0)
        assert a < p1, "placeholder not inside #panel-abl-memory"
        b = h.index("</div>", h.index("placeholder__text", a)) + len("</div>")
    a = h.rindex("\n", 0, a) + 1
    path.write_text(h[:a] + new + h[b:])


def frames(outdir, ck, els, n=10):
    import cairosvg
    from PIL import Image, ImageDraw
    tiles = []
    for i in range(n):
        t = ck.cycle * (i + 0.5) / n if i < n - 1 else ck.hold
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VB_W} {VB_H}" width="{VB_W}" height="{VB_H}">'
               f'<rect width="100%" height="100%" fill="{SPACE}"/>' + "".join(sa.render(e, "frame", t) for e in els)
               + "</svg>")
        img = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode()))).convert("RGB")
        tile = Image.new("RGB", (VB_W, VB_H + 18), "white")
        ImageDraw.Draw(tile).text((6, 3), f"t = {t:.1f} / {ck.cycle:.1f} s", fill=(20, 20, 20))
        tile.paste(img, (0, 18))
        tiles.append(tile)
    cols, gap = 2, 12
    rows = (len(tiles) + cols - 1) // cols
    tw, th = tiles[0].size
    sheet = Image.new("RGB", (cols * tw + (cols - 1) * gap, rows * th + (rows - 1) * gap), (150, 156, 166))
    for i, tile in enumerate(tiles):
        sheet.paste(tile, ((i % cols) * (tw + gap), (i // cols) * (th + gap)))
    outdir.mkdir(parents=True, exist_ok=True)
    p = outdir / "memory_ablation_frames.png"
    sheet.save(p)
    return p


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--html", type=Path, default=DEF_HTML)
    ap.add_argument("--css", type=Path, default=DEF_CSS)
    ap.add_argument("--frames", type=Path)
    args = ap.parse_args()
    cols, rows = parse_tex()
    ck, els = build()
    ids = [x.uid for x in sa.walk(els)]
    assert len(ids) == len(set(ids)), "duplicate element ids"
    patch_html(args.html, html_block(ck, els, cols, rows))
    cb = css_block(ck, els)
    c = args.css.read_text()
    if BEGIN_C in c:
        a, b = c.index(BEGIN_C), c.index(END_C) + len(END_C)
        c = c[:a] + cb + c[b:]
    else:
        c = c.rstrip("\n") + "\n\n" + cb + "\n"
    args.css.write_text(c)
    print(f"cycle {ck.cycle:.1f}s, {len(ids)} animated elements, css block {len(cb) / 1024:.1f} KB")
    if args.frames:
        print("frames:", frames(args.frames, ck, els))


if __name__ == "__main__":
    main()
