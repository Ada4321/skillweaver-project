def parse_tex():
    t = TEX.read_text(encoding="utf-8")
    i = t.index(r"\label{tab:memory-ablation}")
    blk = t[t.rindex(r"\begin{tabular}", 0, i):i]
    head = re.search(r"Method(.*?)\\\\", blk, re.S).group(1)
    cols = [re.sub(r"\s+", " ", c.replace(r"$\rightarrow$", "&rarr;")).strip() for c in head.split("&") if c.strip()]
    unbest = lambda c: re.sub(r"\\best\{([^}]*)\}", r"\1", c).strip()
    rows = [(m.group(1).strip(), [unbest(c) for c in m.group(2).split("&")])
            for m in re.finditer(r"\n\s*(w/o? Memory)\s*&([^\n]*?)\\\\", blk)]
    if len(rows) != 2 or any(len(v) != len(cols) for _, v in rows):
        sys.exit("unexpected shape in tab:memory-ablation")
    return cols, rows


def chart(cols, rows):
    """tab:memory-ablation as grouped bars: one pair per task, average last."""
    wo, w = dict(rows)["w/o Memory"], dict(rows)["w/ Memory"]
    svg = chartlib.grouped_bars(
        name="memAbl", gradient="memAblBar",
        groups=[c.replace("&rarr;", "&rarr;\u200b") for c in cols],
        series=[{"label": name, "cls": "bar--gt" if name == "w/o Memory" else "bar--ours",
                 "values": [float(v) for v in vals]} for name, vals in rows],
        ylab="MCTS success rate (%)", atitle="Task", ymax=108,
        grid=(0, 25, 50, 75, 100), fmt="%.1f", vb_w=660, bar_w=34,
        title="Search success with and without experience memory",
        desc="MCTS success rate per task: " + "; ".join(
            "%s %s" % (n, ", ".join("%s %s%%" % (c, v) for c, v in zip(cols, vals)))
            for n, vals in rows) + ".")
    return (['<figure class="figure">',
             '  <div class="chart-wrap chart-wrap--sm" role="region" tabindex="0" aria-label="Search success with and without '
             'memory">']
            + [svg] + ['  </div>', '</figure>',
             '<p class="table-note">MCTS success rate (%) over ten searches per task at maximum depth <i>K</i> = 6, on '
             'tasks that hinge on orientation adjustment, spatial reasoning, or an implicit prerequisite. <b>Memory '
             f'lifts average search success from {wo[-1]}% to {w[-1]}%.</b></p>'])


